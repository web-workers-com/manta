//! Shell integration: tiny generated rc files that load the user's own rc
//! files unchanged and then add a prompt hook reporting the cwd (OSC 7) and
//! prompt readiness (OSC 133;A), plus private key bindings: one parks the
//! user's half-typed command line while we type a `cd`, another prints the
//! lines of a spool file (GUI file actions) above the prompt.

use std::io;
use std::path::{Path, PathBuf};

use crate::escape::{quote, ShellKind};

/// Private key sequence bound by the shims to "save and clear the input".
pub const PUSH_KEY: &[u8] = b"\x1b[9001~";
/// Bash only: "restore the saved input" (zsh's buffer stack does it itself).
pub const RESTORE_KEY: &[u8] = b"\x1b[9002~";
/// Private key sequence bound by the shims to "print and remove the spool
/// file" (`$MANTA_SPOOL` at startup). Not 9002: bash uses that already.
pub const ECHO_KEY: &[u8] = b"\x1b[9003~";
/// Environment variable telling the shim where the spool file is. The shim
/// moves it into a shell variable so child processes don't inherit it.
pub const SPOOL_ENV: &str = "MANTA_SPOOL";

const ZSH_FILES: [&str; 4] = [".zshenv", ".zprofile", ".zshrc", ".zlogin"];

/// Restore the user's ZDOTDIR and drop our variables (after the last file).
const ZSH_FINISH: &str = r#"if [[ -n ${_MANTA_UZD+x} ]]; then export ZDOTDIR=$_MANTA_UZD; else builtin unset ZDOTDIR; fi
builtin unset _MANTA_UZD MANTA_SHIM_DIR
"#;

const ZSH_HOOKS: &str = r#"if [[ -o interactive && -z ${_manta_hooked-} ]]; then
  typeset -g _manta_hooked=1
  typeset -g _manta_spool=${MANTA_SPOOL-}
  builtin unset MANTA_SPOOL
  if builtin zmodload -F zsh/files b:zf_rm 2>/dev/null; then
    typeset -g _manta_rm=zf_rm
  else
    typeset -g _manta_rm='command rm'
  fi
  setopt HIST_IGNORE_SPACE
  _manta_bind() {
    builtin local km
    for km in emacs viins vicmd; do
      builtin bindkey -M $km '\e[9001~' _manta_push 2>/dev/null
      builtin bindkey -M $km '\e[9003~' _manta_echo 2>/dev/null
    done
  }
  _manta_push() {
    zle push-input
    zle -K main 2>/dev/null
  }
  zle -N _manta_push
  _manta_echo() {
    [[ -n $_manta_spool && -r $_manta_spool ]] || return 0
    # Redraw the prompt without the input, step below it, then go back up
    # over the prompt and print there: the lines replace the prompt, which
    # zle draws again below them with the input restored.
    builtin local buf=$BUFFER cur=$CURSOR p=${(%)PS1}
    builtin local up=$(( ${#p} - ${#${p//$'\n'/}} + 1 ))
    BUFFER=
    zle -R
    zle -I
    builtin print -rn -- $'\e['$up$'A\r\e[J'"$(<$_manta_spool)"$'\n'
    ${=_manta_rm} -f -- $_manta_spool
    BUFFER=$buf
    CURSOR=$cur
  }
  zle -N _manta_echo
  _manta_precmd() {
    builtin local p=${PWD//[%]/%25}
    p=${p// /%20}
    builtin printf '\e]7;file://%s%s\a\e]133;A;manta=push%s\a' "${HOST}" "${p}" "${_manta_spool:+;manta-echo}"
    _manta_bind
    _manta_hook_themes
    _manta_wrap_rprompt
  }
  # Themes that rebuild RPROMPT after every other precmd hook: wrap the
  # function that builds it. powerlevel10k keeps its precmd last and sets
  # RPROMPT in _p9k_set_prompt.
  _manta_hook_themes() {
    if (( $+functions[_p9k_set_prompt] && ! $+functions[_manta_orig_p9k_set_prompt] )); then
      functions[_manta_orig_p9k_set_prompt]=$functions[_p9k_set_prompt]
      _p9k_set_prompt() {
        _manta_orig_p9k_set_prompt "$@"
        builtin local ret=$?
        _manta_wrap_rprompt
        return ret
      }
    fi
  }
  # Mark RPROMPT with zero-width private OSCs so the terminal knows which
  # cells are the right prompt and can keep it right-aligned on history
  # lines at any width. Runs every prompt (themes may rebuild RPROMPT).
  _manta_wrap_rprompt() {
    [[ -o promptpercent && -n $RPROMPT ]] || return 0
    [[ $RPROMPT == *$'\e]7701;s\a'* ]] && return 0
    RPROMPT=$'%{\e]7701;s\a%}'"${RPROMPT}"$'%{\e]7701;e\a%}'
  }
  _manta_preexec() {
    builtin printf '\e]133;C\a'
    # A command line mentioning ssh (aliases expanded): the terminal may
    # offer to open that server in the pane. Control characters are dropped
    # so the sequence can't be cut short.
    [[ $2 == *ssh* ]] && builtin printf '\e]7702;%s\a' "${2//[[:cntrl:]]/ }"
    builtin return 0
  }
  builtin autoload -Uz add-zsh-hook
  add-zsh-hook precmd _manta_precmd
  add-zsh-hook preexec _manta_preexec
fi
"#;

/// Contents of one zsh shim file.
pub fn zsh_shim(file: &str) -> String {
    let mut s = String::from(
        "# Generated by Manta (terminal shell integration). Do not edit.\n\
         # Loads your own file from $ZDOTDIR or $HOME first, unchanged.\n",
    );
    s.push_str(
        "if [[ -n ${_MANTA_UZD+x} ]]; then ZDOTDIR=$_MANTA_UZD; else builtin unset ZDOTDIR; fi\n",
    );
    if file == ".zshrc" {
        // macOS /etc/zshrc set HISTFILE from our ZDOTDIR: point it home.
        s.push_str(
            "if [[ $HISTFILE == ${MANTA_SHIM_DIR}/* ]]; then HISTFILE=${ZDOTDIR:-$HOME}/.zsh_history; fi\n",
        );
    }
    s.push_str(&format!(
        "if [[ -r \"${{ZDOTDIR:-$HOME}}/{file}\" ]]; then builtin source \"${{ZDOTDIR:-$HOME}}/{file}\"; fi\n"
    ));
    s.push_str(
        "if [[ -n ${ZDOTDIR+x} ]]; then _MANTA_UZD=$ZDOTDIR; else builtin unset _MANTA_UZD; fi\n",
    );
    match file {
        ".zshrc" => {
            s.push_str(ZSH_HOOKS);
            s.push_str("if [[ -o login ]]; then ZDOTDIR=$MANTA_SHIM_DIR; else\n");
            s.push_str(ZSH_FINISH);
            s.push_str("fi\n");
        }
        ".zlogin" => s.push_str(ZSH_FINISH),
        _ => s.push_str("ZDOTDIR=$MANTA_SHIM_DIR\n"),
    }
    s
}

/// The `--rcfile` for bash: emulate a login shell's startup files, then hook
/// `PROMPT_COMMAND`.
pub fn bash_shim() -> String {
    r#"# Generated by Manta (terminal shell integration). Do not edit.
# Bash reads --rcfile instead of your startup files, so load them like a
# login shell would.
if [ -r /etc/profile ]; then . /etc/profile; fi
if [ -r "$HOME/.bash_profile" ]; then . "$HOME/.bash_profile"
elif [ -r "$HOME/.bash_login" ]; then . "$HOME/.bash_login"
elif [ -r "$HOME/.profile" ]; then . "$HOME/.profile"
elif [ -r "$HOME/.bashrc" ]; then . "$HOME/.bashrc"
fi
HISTCONTROL="${HISTCONTROL:+$HISTCONTROL:}ignorespace"
__manta_spool=${MANTA_SPOOL-}
unset MANTA_SPOOL
__manta_prompt() {
  local ret=$? p=${PWD//[%]/%25}
  p=${p// /%20}
  printf '\033]7;file://%s%s\007\033]133;A;%s\007' "$HOSTNAME" "$p" "$__manta_cap"
  return $ret
}
if [ "${BASH_VERSINFO[0]:-0}" -ge 4 ]; then
  __manta_cap='manta=push'
  __manta_save() {
    __manta_line=$READLINE_LINE; __manta_point=$READLINE_POINT
    READLINE_LINE=; READLINE_POINT=0
  }
  __manta_restore() {
    READLINE_LINE=$__manta_line; READLINE_POINT=${__manta_point:-0}
    __manta_line=; __manta_point=0
  }
  for __manta_km in emacs vi-insert vi-command; do
    bind -m "$__manta_km" -x '"\e[9001~": __manta_save' 2>/dev/null
    bind -m "$__manta_km" -x '"\e[9002~": __manta_restore' 2>/dev/null
  done
  unset __manta_km
else
  __manta_cap='manta=basic'
fi
__manta_echo() {
  [ -n "$__manta_spool" ] && [ -r "$__manta_spool" ] || return 0
  command cat -- "$__manta_spool"
  command rm -f -- "$__manta_spool"
}
if [ -n "$__manta_spool" ]; then
  if [ "${BASH_VERSINFO[0]:-0}" -ge 4 ]; then
    for __manta_km in emacs vi-insert vi-command; do
      bind -m "$__manta_km" -x '"\e[9003~": __manta_echo' 2>/dev/null
    done
    unset __manta_km
  else
    # bash 3.2 runs `bind -x` commands only for one key or a C-x/ESC pair:
    # route the private key through a macro (emacs keymap only).
    bind -x '"\C-x\C-_": __manta_echo' 2>/dev/null
    bind '"\e[9003~": "\C-x\C-_"' 2>/dev/null
  fi
  __manta_cap="$__manta_cap;manta-echo"
fi
case "$(declare -p PROMPT_COMMAND 2>/dev/null)" in
  "declare -a"*) PROMPT_COMMAND=(__manta_prompt "${PROMPT_COMMAND[@]}") ;;
  *) PROMPT_COMMAND="__manta_prompt${PROMPT_COMMAND:+; $PROMPT_COMMAND}" ;;
esac
"#
    .to_owned()
}

/// Paths of the generated integration for one shell.
#[derive(Debug, Clone)]
pub struct ShimPaths {
    pub zsh_dir: PathBuf,
    pub bash_rc: PathBuf,
}

/// Write (or refresh) the shim files below `root`.
pub fn install(root: &Path) -> io::Result<ShimPaths> {
    let zsh_dir = root.join("zsh");
    std::fs::create_dir_all(&zsh_dir)?;
    for f in ZSH_FILES {
        write_if_changed(&zsh_dir.join(f), &zsh_shim(f))?;
    }
    let bash_dir = root.join("bash");
    std::fs::create_dir_all(&bash_dir)?;
    let bash_rc = bash_dir.join("rc.bash");
    write_if_changed(&bash_rc, &bash_shim())?;
    Ok(ShimPaths { zsh_dir, bash_rc })
}

fn write_if_changed(path: &Path, content: &str) -> io::Result<()> {
    if std::fs::read_to_string(path).ok().as_deref() == Some(content) {
        return Ok(());
    }
    std::fs::write(path, content)
}

/// How much of the integration a running shell has announced.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Integration {
    /// Our prompt marker with the private push/restore keys.
    Push,
    /// Prompt marker only (bash 3.2).
    Basic,
    /// No marker seen (unsupported shell, or the rc files replaced the shell).
    None,
}

/// The bytes to type so the shell changes to `path`, keeping whatever the
/// user had typed at the prompt.
pub fn cd_input(kind: ShellKind, integration: Integration, path: &str) -> Vec<u8> {
    let q = quote(path, kind);
    let cmd = match kind {
        ShellKind::Fish => format!(" cd {q}\r"),
        _ => format!(" cd -- {q}\r"),
    };
    let mut out = Vec::new();
    match (kind, integration) {
        (ShellKind::Zsh, Integration::Push) => {
            out.extend_from_slice(PUSH_KEY);
            out.extend_from_slice(cmd.as_bytes());
        }
        (ShellKind::Zsh, _) => {
            // ESC q = push-line in zsh's emacs keymap.
            out.extend_from_slice(b"\x1bq");
            out.extend_from_slice(cmd.as_bytes());
        }
        (ShellKind::Bash, Integration::Push) => {
            out.extend_from_slice(PUSH_KEY);
            out.extend_from_slice(cmd.as_bytes());
            out.extend_from_slice(RESTORE_KEY);
        }
        _ => {
            // Ctrl-E Ctrl-U: end of line, kill to start.
            out.extend_from_slice(b"\x05\x15");
            out.extend_from_slice(cmd.as_bytes());
        }
    }
    out
}

/// The bytes to type so the shell runs `command` like a typed command line
/// (it shows on screen and lands in the history), keeping whatever the user
/// had typed at the prompt: zsh's buffer stack brings it back after the
/// command, bash 4+ gets it restored by the private key. Shells without
/// the push key lose the half-typed line (as with [`cd_input`]).
pub fn run_input(kind: ShellKind, integration: Integration, command: &str) -> Vec<u8> {
    // A leading space would hide it from the history (HIST_IGNORE_SPACE /
    // ignorespace); trailing newlines would submit empty lines.
    let cmd = format!("{}\r", command.trim_start().trim_end_matches(['\n', '\r']));
    let mut out = Vec::new();
    match (kind, integration) {
        (ShellKind::Zsh, Integration::Push) => {
            out.extend_from_slice(PUSH_KEY);
            out.extend_from_slice(cmd.as_bytes());
        }
        (ShellKind::Zsh, _) => {
            out.extend_from_slice(b"\x1bq");
            out.extend_from_slice(cmd.as_bytes());
        }
        (ShellKind::Bash, Integration::Push) => {
            out.extend_from_slice(PUSH_KEY);
            out.extend_from_slice(cmd.as_bytes());
            out.extend_from_slice(RESTORE_KEY);
        }
        _ => {
            out.extend_from_slice(b"\x05\x15");
            out.extend_from_slice(cmd.as_bytes());
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn zsh_shims_source_user_files_and_restore() {
        for f in ZSH_FILES {
            let s = zsh_shim(f);
            assert!(
                s.contains(&format!("builtin source \"${{ZDOTDIR:-$HOME}}/{f}\"")),
                "{f}"
            );
            assert!(s.contains("_MANTA_UZD"), "{f}");
        }
        assert!(zsh_shim(".zshenv").ends_with("ZDOTDIR=$MANTA_SHIM_DIR\n"));
        assert!(zsh_shim(".zprofile").ends_with("ZDOTDIR=$MANTA_SHIM_DIR\n"));
        let rc = zsh_shim(".zshrc");
        assert!(rc.contains("setopt HIST_IGNORE_SPACE"));
        assert!(rc.contains("add-zsh-hook precmd _manta_precmd"));
        assert!(rc.contains("\\e]7;file://"));
        assert!(rc.contains("\\e]133;A"));
        assert!(rc.contains("HISTFILE"));
        // RPROMPT wrapped in the private markers every prompt, also for
        // powerlevel10k which rebuilds it after every other precmd hook.
        assert!(rc.contains("RPROMPT=$'%{\\e]7701;s\\a%}'\"${RPROMPT}\"$'%{\\e]7701;e\\a%}'"));
        assert!(rc.contains("functions[_manta_orig_p9k_set_prompt]=$functions[_p9k_set_prompt]"));
        assert!(rc.contains("bindkey -M $km '\\e[9003~' _manta_echo"));
        assert!(rc.contains("zle -I"));
        assert!(rc.contains("manta-echo"));
        // Hooks come after the user's rc so its prompt/plugins load first.
        assert!(rc.find("builtin source").unwrap() < rc.find("add-zsh-hook").unwrap());
        assert!(zsh_shim(".zlogin").contains("export ZDOTDIR=$_MANTA_UZD"));
    }

    #[test]
    fn bash_shim_hooks_prompt_command() {
        let s = bash_shim();
        assert!(s.contains(". \"$HOME/.bash_profile\""));
        assert!(s.contains("ignorespace"));
        assert!(s.contains("PROMPT_COMMAND=\"__manta_prompt"));
        assert!(s.contains("\\e[9001~"));
        assert!(s.contains("\\e[9003~\": __manta_echo"));
        assert!(s.contains("manta-echo"));
        assert!(s.contains("return $ret"));
    }

    #[test]
    fn shims_are_valid_shell_syntax() {
        let dir = tempfile::tempdir().unwrap();
        let paths = install(dir.path()).unwrap();
        if Path::new("/bin/zsh").exists() {
            for f in ZSH_FILES {
                let st = std::process::Command::new("/bin/zsh")
                    .arg("-n")
                    .arg(paths.zsh_dir.join(f))
                    .status()
                    .unwrap();
                assert!(st.success(), "zsh -n {f}");
            }
        }
        if Path::new("/bin/bash").exists() {
            let st = std::process::Command::new("/bin/bash")
                .arg("-n")
                .arg(&paths.bash_rc)
                .status()
                .unwrap();
            assert!(st.success(), "bash -n");
        }
    }

    #[test]
    fn cd_inputs() {
        assert_eq!(
            cd_input(ShellKind::Zsh, Integration::Push, "/tmp/it's"),
            b"\x1b[9001~ cd -- '/tmp/it'\\''s'\r".to_vec()
        );
        assert_eq!(
            cd_input(ShellKind::Zsh, Integration::None, "/a"),
            b"\x1bq cd -- '/a'\r".to_vec()
        );
        assert_eq!(
            cd_input(ShellKind::Bash, Integration::Push, "/a b"),
            b"\x1b[9001~ cd -- '/a b'\r\x1b[9002~".to_vec()
        );
        assert_eq!(
            cd_input(ShellKind::Bash, Integration::Basic, "/a"),
            b"\x05\x15 cd -- '/a'\r".to_vec()
        );
        assert_eq!(
            cd_input(ShellKind::Fish, Integration::None, "/a"),
            b"\x05\x15 cd '/a'\r".to_vec()
        );
    }

    #[test]
    fn run_inputs() {
        assert_eq!(
            run_input(ShellKind::Zsh, Integration::Push, "  ls -la\n"),
            b"\x1b[9001~ls -la\r".to_vec()
        );
        assert_eq!(
            run_input(ShellKind::Zsh, Integration::None, "make"),
            b"\x1bqmake\r".to_vec()
        );
        assert_eq!(
            run_input(ShellKind::Bash, Integration::Push, "echo 'a b'"),
            b"\x1b[9001~echo 'a b'\r\x1b[9002~".to_vec()
        );
        assert_eq!(
            run_input(ShellKind::Fish, Integration::None, "ls"),
            b"\x05\x15ls\r".to_vec()
        );
    }
}
